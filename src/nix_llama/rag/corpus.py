"""Corpus assembly from a source manifest.

Every document that reaches the index -- and therefore every document that
could reach the model -- comes in through here, and the licence allowlist below
is the gate. ``build_corpus`` refuses to index a source whose licence is not on
the list, so "only train on and retrieve from material we are permitted to use"
is enforced by the build rather than by a note in the README.

The manifest is generated by ``nix/model/sources.nix`` and looks like::

    {"sources": [{"name": "nixpkgs-manual", "license": "MIT",
                  "homepage": "https://github.com/NixOS/nixpkgs",
                  "rev": "...", "root": "/nix/store/...",
                  "include": ["doc/**/*.md"], "exclude": ["**/release-notes/**"]}]}
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..nixopts import options_from_nix
from .index import Chunk, chunk_document, clean_markup

# Licences under which redistribution and derivative works -- which is what
# both indexing and fine-tuning are -- are unambiguously permitted.
#
# Deliberately excluded: GFDL (Arch Wiki), CC-BY-NC-*, CC-BY-ND-*, anything
# unlicensed or "all rights reserved", and proprietary vendor documentation
# (Apple's included).
#
# Copyleft documentation licences (CC-BY-SA, GPL, LGPL, MPL) are on the list
# but are recorded as share-alike, and the corpus policy restricts them to
# retrieval. Quoting them with attribution is exactly what their grant allows;
# folding them into model weights, where the share-alike obligation cannot be
# honoured, is not.
LICENSE_ALLOWLIST = frozenset(
    {
        "0BSD",
        "APACHE-2.0",
        "BSD-2-CLAUSE",
        "BSD-3-CLAUSE",
        "CC-BY-3.0",
        "CC-BY-4.0",
        "CC-BY-SA-3.0",
        "CC-BY-SA-4.0",
        "CC0-1.0",
        "GPL-2.0",
        "GPL-2.0-OR-LATER",
        "GPL-3.0",
        "GPL-3.0-OR-LATER",
        "ISC",
        "LGPL-2.1",
        "MIT",
        "MPL-2.0",
        "PUBLIC-DOMAIN",
        "UNLICENSE",
        "ZLIB",
    }
)

# Licences that require downstream works to carry the same terms. Recorded so
# ATTRIBUTION.md can say so explicitly.
SHARE_ALIKE = frozenset(
    {
        "CC-BY-SA-3.0",
        "CC-BY-SA-4.0",
        "GPL-2.0",
        "GPL-2.0-OR-LATER",
        "GPL-3.0",
        "GPL-3.0-OR-LATER",
        "LGPL-2.1",
        "MPL-2.0",
    }
)

DEFAULT_INCLUDE = ["**/*.md", "**/*.markdown", "**/*.rst", "**/*.txt", "**/*.adoc"]


class LicenseError(Exception):
    """Raised when a source's licence is not on the allowlist."""


@dataclass
class Source:
    name: str
    license: str
    root: str
    homepage: str = ""
    rev: str = ""
    include: list[str] = field(default_factory=lambda: list(DEFAULT_INCLUDE))
    exclude: list[str] = field(default_factory=list)
    url_template: str = ""
    description: str = ""

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Source:
        known = set(cls.__dataclass_fields__)
        unknown = set(data) - known
        if unknown:
            raise ValueError(f"unknown manifest keys for source: {', '.join(sorted(unknown))}")
        return cls(**data)

    @property
    def normalized_license(self) -> str:
        return self.license.strip().upper()

    def validate(self) -> None:
        if self.normalized_license not in LICENSE_ALLOWLIST:
            raise LicenseError(
                f"source {self.name!r} is licensed {self.license!r}, which is not on the "
                f"nix-llama allowlist. Training on or redistributing material we lack "
                f"permission for is out of scope for this project; drop the source or "
                f"justify adding the licence to LICENSE_ALLOWLIST."
            )

    def file_url(self, relative: str) -> str:
        if self.url_template:
            return self.url_template.replace("{path}", relative).replace("{rev}", self.rev)
        return self.homepage

    def files(self) -> list[Path]:
        root = Path(self.root)
        if root.is_file():
            return [root]
        seen: dict[str, Path] = {}
        for pattern in self.include:
            for path in root.glob(pattern):
                if path.is_file():
                    seen[str(path.relative_to(root))] = path
        for pattern in self.exclude:
            for path in root.glob(pattern):
                seen.pop(str(path.relative_to(root)), None)
        # Sorted so the corpus -- and therefore the index -- is reproducible.
        return [seen[key] for key in sorted(seen)]


def load_manifest(path: str | Path) -> list[Source]:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    sources = [Source.from_dict(item) for item in data.get("sources", [])]
    if not sources:
        raise ValueError(f"{path} lists no sources")
    return sources


def build_corpus(
    sources: list[Source], *, verbose: bool = False
) -> tuple[list[Chunk], dict[str, dict[str, str]]]:
    """Chunk every file in every source, enforcing the licence allowlist."""
    chunks: list[Chunk] = []
    metadata: dict[str, dict[str, str]] = {}
    for source in sources:
        source.validate()
        files = source.files()
        if not files:
            # Silently shipping an empty index is worse than failing: the
            # server would start, answer, and never cite anything.
            raise ValueError(
                f"source {source.name!r} matched no files under {source.root!r} "
                f"with include patterns {source.include}. Check the path, the glob "
                f"patterns, and that the source was actually fetched."
            )
        start = len(chunks)
        root = Path(source.root)
        for path in files:
            try:
                raw = path.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            text = clean_markup(raw)
            if not text:
                continue
            relative = str(path.relative_to(root)) if root.is_dir() else path.name

            if path.suffix == ".nix":
                # A module's value is its option declarations, not its
                # implementation. One chunk per documented option makes
                # `services.openssh.enable` retrievable by name, which 1400
                # characters of surrounding Nix does not.
                chunks.extend(option_chunks(source, relative, text))
                continue

            chunks.extend(
                chunk_document(
                    text,
                    doc_id=f"{source.name}:{relative}",
                    title=_title_for(text, path),
                    source=source.name,
                    license=source.license,
                    url=source.file_url(relative),
                    path=relative,
                )
            )
        metadata[source.name] = {
            "license": source.license,
            "homepage": source.homepage,
            "rev": source.rev,
            "files": str(len(files)),
            "chunks": str(len(chunks) - start),
            "share_alike": "yes" if source.normalized_license in SHARE_ALIKE else "no",
        }
        if verbose:
            print(
                f"{source.name}: {len(files)} files -> {len(chunks) - start} chunks "
                f"({source.license})"
            )
    return chunks, metadata


def option_chunks(source: Source, relative: str, text: str) -> list[Chunk]:
    """Turn a Nix module's documented options into retrievable chunks."""
    chunks: list[Chunk] = []
    for index, option in enumerate(options_from_nix(text, prefix_hint=source.name)):
        name = option["name"]
        if "." not in name:
            # An option whose path could not be reconstructed cannot be cited
            # usefully, so it is not worth indexing.
            continue
        lines = [f"{name}", "", option["description"]]
        for label, key in (("Type", "type"), ("Default", "default"), ("Example", "example")):
            if option.get(key):
                lines.append(f"{label}: {option[key]}")
        chunks.append(
            Chunk(
                id=f"{source.name}:{relative}#opt{index}",
                text="\n".join(lines),
                title=name,
                source=source.name,
                license=source.license,
                url=source.file_url(relative),
                path=relative,
            )
        )
    return chunks


def _title_for(text: str, path: Path) -> str:
    """Use the document's first heading, falling back to its filename."""
    for line in text.splitlines()[:40]:
        stripped = line.strip()
        if stripped.startswith("#"):
            return stripped.lstrip("#").strip() or path.stem
        if stripped.startswith("title:"):
            return stripped.split(":", 1)[1].strip().strip("\"'") or path.stem
    return path.stem.replace("-", " ").replace("_", " ")


def attribution(metadata: dict[str, dict[str, str]]) -> str:
    """Render the attribution notice that ships with the model."""
    lines = [
        "# Attribution",
        "",
        "nix-llama's documentation corpus -- used both for the retrieval index and as",
        "fine-tuning material -- is built exclusively from sources whose licences permit",
        "redistribution and derivative works. Each source is listed below with the",
        "licence and upstream revision it was built from.",
        "",
    ]
    share_alike = sorted(k for k, v in metadata.items() if v.get("share_alike") == "yes")
    for name, meta in sorted(metadata.items()):
        lines.append(f"## {name}")
        lines.append("")
        lines.append(f"- Licence: {meta.get('license', 'unknown')}")
        if meta.get("homepage"):
            lines.append(f"- Upstream: {meta['homepage']}")
        if meta.get("rev"):
            lines.append(f"- Revision: `{meta['rev']}`")
        lines.append(f"- Indexed: {meta.get('files', '0')} files, {meta.get('chunks', '0')} chunks")
        lines.append("")
    if share_alike:
        lines += [
            "## Share-alike notice",
            "",
            "The following sources are under share-alike licences. Material derived from",
            "them -- including this model's retrieval index and any text it reproduces from",
            "them -- carries the same licence terms:",
            "",
            *[f"- {name} ({metadata[name]['license']})" for name in share_alike],
            "",
        ]
    return "\n".join(lines)
